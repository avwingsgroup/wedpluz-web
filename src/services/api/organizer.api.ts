import { request } from '@/services/http'
import type {
  ActivityLogEntry,
  CheckInRecord,
  Community,
  CommunityPermissions,
  Event,
  EventCollaboration,
  EventDraftPayload,
  EventManager,
  EventPromotionSettings,
  EventRequest,
  EventTask,
  EventVendorAssignment,
  GuestListEntry,
  ManageEventSummary,
  ManagerPermission,
  OrganizerAnalytics,
  PromoterBoardEntry,
  PromoterEnrollment,
  TaskPayload,
  TicketValidationResult,
} from '@/types'

export type ManagedEvent = Event & { manage: ManageEventSummary }

export const organizerApi = {
  list: (params: { tab?: 'created' | 'team'; status?: string; search?: string; page?: number }) => request.getPaginated<ManageEventSummary>('/organizer/events', params),
  createDraft: (payload: Partial<EventDraftPayload>) => request.post<Event>('/organizer/events', payload),
  get: (id: string) => request.get<ManagedEvent>(`/organizer/events/${id}`),
  update: (id: string, payload: Partial<EventDraftPayload>) => request.put<Event>(`/organizer/events/${id}`, payload),
  publish: (id: string) => request.post<Event>(`/organizer/events/${id}/publish`),
  remove: (id: string) => request.del(`/organizer/events/${id}`),
  setStatus: (id: string, payload: { status: 'completed' | 'cancelled'; cancellationReason?: string }) => request.patch<Event>(`/organizer/events/${id}/status`, payload),
  analytics: (id: string) => request.get<OrganizerAnalytics>(`/organizer/events/${id}/analytics`),
  guests: (id: string, params: { filter?: string; search?: string; page?: number }) => request.getPaginated<GuestListEntry>(`/organizer/events/${id}/guests`, params),
  requests: (id: string, status = 'pending') => request.getPaginated<EventRequest>(`/organizer/events/${id}/requests`, { status, perPage: 50 }),
  decideRequest: (id: string, requestId: string, status: 'approved' | 'declined') => request.patch<EventRequest>(`/organizer/events/${id}/requests/${requestId}`, { status }),
  bulkDecide: (id: string, ids: string[], status: 'approved' | 'declined') => request.post<{ updated: number }>(`/organizer/events/${id}/requests/bulk`, { ids, status }),
  checkIns: (id: string, page = 1) => request.getPaginated<CheckInRecord>(`/organizer/events/${id}/check-ins`, { page }),
  validateTicket: (id: string, payload: { code: string; method: 'scan' | 'manual' }) => request.post<TicketValidationResult>(`/organizer/events/${id}/check-ins`, payload),
  managers: (id: string, search?: string) => request.get<EventManager[]>(`/organizer/events/${id}/managers`, { search }),
  inviteManager: (id: string, payload: { userId?: string; email?: string; access: 'full' | 'partial'; permissions: ManagerPermission[] }) => request.post<EventManager>(`/organizer/events/${id}/managers`, payload),
  updateManager: (id: string, managerId: string, payload: Partial<Pick<EventManager, 'access' | 'permissions'>>) => request.patch<EventManager>(`/organizer/events/${id}/managers/${managerId}`, payload),
  removeManager: (id: string, managerId: string) => request.del(`/organizer/events/${id}/managers/${managerId}`),
  vendors: (id: string, search?: string) => request.get<EventVendorAssignment[]>(`/organizer/events/${id}/vendors`, { search }),
  inviteVendor: (id: string, payload: { vendorId: string; role?: string }) => request.post<EventVendorAssignment>(`/organizer/events/${id}/vendors`, payload),
  removeVendor: (id: string, assignmentId: string) => request.del(`/organizer/events/${id}/vendors/${assignmentId}`),
  tasks: (id: string, params: { assigneeId?: string; search?: string; sort?: 'due' | 'created' } = {}) => request.get<EventTask[]>(`/organizer/events/${id}/tasks`, params),
  createTask: (id: string, payload: TaskPayload) => request.post<EventTask, TaskPayload>(`/organizer/events/${id}/tasks`, payload),
  updateTask: (id: string, taskId: string, payload: Partial<TaskPayload>) => request.patch<EventTask>(`/organizer/events/${id}/tasks/${taskId}`, payload),
  deleteTask: (id: string, taskId: string) => request.del(`/organizer/events/${id}/tasks/${taskId}`),
  activity: (id: string, role: string = 'all', page = 1) => request.getPaginated<ActivityLogEntry>(`/organizer/events/${id}/activity`, { role, page }),
  promotion: (id: string) => request.get<EventPromotionSettings>(`/organizer/events/${id}/promotion`),
  updatePromotion: (id: string, payload: Partial<EventPromotionSettings>) => request.put<EventPromotionSettings>(`/organizer/events/${id}/promotion`, payload),
  promoters: (id: string) => request.get<PromoterBoardEntry[]>(`/organizer/events/${id}/promoters`),
  community: (id: string) => request.get<Community | null>(`/organizer/events/${id}/community`),
  updateCommunity: (id: string, payload: { enabled: boolean; permissions?: Partial<CommunityPermissions> }) => request.put<Community | null>(`/organizer/events/${id}/community`, payload),
  collaborations: () => request.get<EventCollaboration[]>('/me/collaborations'),
  respondCollaboration: (id: string, status: 'accepted' | 'declined') => request.patch<EventCollaboration>(`/me/collaborations/${id}`, { status }),
  promotions: (params: { status?: 'active' | 'past'; search?: string; page?: number }) => request.getPaginated<PromoterEnrollment>('/me/promotions', params),
  promotionDetail: (id: string) => request.get<PromoterEnrollment>(`/me/promotions/${id}`),
  joinPromotion: (eventId: string) => request.post<PromoterEnrollment>(`/events/${eventId}/promotions/join`),
}
